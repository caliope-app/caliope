// Generates web/lib/icons.js from the Lucide icon package (ISC license).
// Usage: node tools/build-icons.mjs <path to node_modules/lucide>
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const ICONS = [
  'plus', 'search', 'folder', 'folder-open', 'folder-tree', 'git-branch', 'git-fork', 'git-pull-request', 'settings', 'chevron-down', 'chevron-right',
  'chevron-left', 'square', 'arrow-up', 'arrow-down', 'check', 'x', 'circle-alert', 'triangle-alert', 'terminal', 'file-text',
  'file-pen', 'file-plus', 'files', 'globe', 'list-todo', 'sparkles', 'copy', 'ellipsis', 'pin', 'pin-off', 'archive',
  'archive-restore', 'trash-2', 'rotate-ccw', 'download', 'panel-right', 'panel-left', 'image', 'brain', 'message-square',
  'shield-check', 'shield-alert', 'loader-circle', 'log-out', 'wallet', 'chart-column', 'refresh-cw', 'external-link', 'info',
  'map', 'user', 'key-round', 'zap', 'hand', 'pencil', 'circle-check', 'circle', 'circle-dot',
  'lightbulb', 'coins', 'gauge', 'history', 'scroll-text', 'text-search', 'layers', 'monitor', 'paperclip', 'square-pen', 'folder-plus',
];

const lucideRoot = process.argv[2];
if (!lucideRoot) {
  console.error('Pass the path to node_modules/lucide.');
  process.exit(1);
}
const output = {};
const missing = [];
for (const name of ICONS) {
  const file = path.join(lucideRoot, 'dist', 'esm', 'icons', `${name}.js`);
  if (!fs.existsSync(file)) {
    missing.push(name);
    continue;
  }
  const module = await import(pathToFileURL(file).href);
  const nodes = module.default;
  output[name] = nodes
    .map(([tag, attributes]) => `<${tag} ${Object.entries(attributes).map(([key, value]) => `${key}="${value}"`).join(' ')}/>`)
    .join('');
}
if (missing.length) console.warn(`Missing icons: ${missing.join(', ')}`);
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'web', 'lib', 'icons.js');
const source = `// Generated by tools/build-icons.mjs from Lucide (https://lucide.dev), ISC license. Do not edit by hand.
const PATHS = ${JSON.stringify(output, null, 2)};

/** SVG markup for an icon; \`size\` in pixels. */
export function icon(name, size = 16, extraClass = '') {
  const paths = PATHS[name] || PATHS['circle'];
  return \`<svg class="icon \${extraClass}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${paths}</svg>\`;
}
`;
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, source);
console.log(`Wrote ${Object.keys(output).length} icons to ${target}`);
